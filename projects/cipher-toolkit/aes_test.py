RCON = [0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36]

def _mul(a, b):
    """Galois Field multiplication under AES polynomial."""
    p = 0
    for _ in range(8):
        if b & 1: p ^= a
        hi = a & 0x80; a = (a << 1) & 0xFF
        if hi: a ^= 0x1B
        b >>= 1
    return p

def _key_expansion(key):
    if len(key) != 16: raise ValueError('AES-128 requires a 16-byte key')
    w = [int.from_bytes(key[i:i+4], 'big') for i in range(0,16,4)]
    rcon_idx = 0
    while len(w) < 44:
        temp = w[-1]
        if len(w) % 4 == 0:
            temp = ((temp << 8) | (temp >> 24)) & 0xFFFFFFFF
            temp = (SBOX[temp >> 24] << 24) | (SBOX[(temp >> 16) & 0xFF] << 16) | (SBOX[(temp >> 8) & 0xFF] << 8) | SBOX[temp & 0xFF]
            temp ^= (RCON[rcon_idx] << 24); rcon_idx += 1
        w.append(w[-4] ^ temp)
    return w

def _add_round_key(state, w, rnd):
    """XOR round key into state. State[row][col], key as 4 words per round."""
    for col in range(4):
        rk_word = w[4 * rnd + col]
        for row in range(4):
            state[row][col] ^= (rk_word >> (24 - 8*row)) & 0xFF
    return state

def _sub_bytes(state):
    for row in range(4):
        for col in range(4):
            state[row][col] = SBOX[state[row][col]]
    return state

def _shift_rows(state):
    # Row r is shifted left by r positions
    for row in range(1, 4):
        tmp = state[row][:]  # copy
        for col in range(4):
            state[row][col] = tmp[(col + row) % 4]
    return state

def _mix_columns(state):
    for col in range(4):
        a0, a1, a2, a3 = state[0][col], state[1][col], state[2][col], state[3][col]
        state[0][col] = _mul(a0, 2) ^ _mul(a1, 3) ^ a2 ^ a3
        state[1][col] = a0 ^ _mul(a1, 2) ^ _mul(a2, 3) ^ a3
        state[2][col] = a0 ^ a1 ^ _mul(a2, 2) ^ _mul(a3, 3)
        state[3][col] = _mul(a0, 3) ^ a1 ^ a2 ^ _mul(a3, 2)
    return state

def _encrypt_block(block):
    if len(block) != 16: raise ValueError('Block must be 16 bytes')
    # Input bytes laid out column-by-column into state[row][col]
    # byte i goes to state[i % 4][i // 4] in column-major layout
    state = [[0]*4 for _ in range(4)]
    for i in range(16):
        state[i % 4][i // 4] = block[i]
    w = _key_expansion(block)
    state = _add_round_key(state, w, 0)
    for rnd in range(1, 10):
        state = _sub_bytes(state)
        state = _shift_rows(state)
        state = _mix_columns(state)
        state = _add_round_key(state, w, rnd)
    state = _sub_bytes(state)
    state = _shift_rows(state)
    state = _add_round_key(state, w, 10)
    # Output: column-by-column from state
    ct = b''
    for col in range(4):
        for row in range(4):
            ct += bytes([state[row][col]])
    return ct

